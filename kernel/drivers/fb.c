void fb_draw_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg) {
    if (!g_fb_addr) return;
    if ((unsigned char)c >= 256) c = '?';

    const uint8_t *glyph = font_8x16[(unsigned char)c];

    for (uint32_t row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (uint32_t col = 0; col < 8; col++) {
            uint32_t color = (bits & 0x80) ? fg : bg;
            fb_put_pixel(x + col, y + row, color);
            bits <<= 1;
        }
    }
}

void fb_draw_string(uint32_t x, uint32_t y, const char *str, uint32_t fg, uint32_t bg) {
    while (*str) {
        fb_draw_char(x, y, *str, fg, bg);
        x += 8;
        str++;
    }
}

void fb_draw_string_centered(uint32_t y, const char *str, uint32_t fg, uint32_t bg) {
    uint32_t len = strlen(str);
    uint32_t x = (g_fb_width > len * 8) ? (g_fb_width - len * 8) / 2 : 0;
    fb_draw_string(x, y, str, fg, bg);
}

/* Draw character to arbitrary buffer (for GUI window rendering) */
void fb_draw_char_to_buffer(uint32_t *buf, uint32_t pitch, int x, int y, char c, uint32_t fg, uint32_t bg) {
    if ((unsigned char)c >= 256) c = '?';
    const uint8_t *glyph = font_8x16[(unsigned char)c];

    for (uint32_t row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (uint32_t col = 0; col < 8; col++) {
            int px = x + col;
            int py = y + row;
            if (px >= 0 && px < (int)pitch && py >= 0 && py < (int)fb_height()) {
                buf[py * pitch + px] = (bits & 0x80) ? fg : bg;
            }
            bits <<= 1;
        }
    }
}

/* ============================================================
 * Blend/Alpha (for dock transparency)
 * ============================================================ */
static inline uint32_t blend_color(uint32_t fg, uint32_t bg, uint8_t alpha) {
    uint32_t r = ((fg >> 16) & 0xFF) * alpha + ((bg >> 16) & 0xFF) * (255 - alpha);
    uint32_t g = ((fg >> 8) & 0xFF) * alpha + ((bg >> 8) & 0xFF) * (255 - alpha);
    uint32_t b = (fg & 0xFF) * alpha + (bg & 0xFF) * (255 - alpha);
    return 0xFF000000 | ((r >> 8) << 16) | ((g >> 8) << 8) | (b >> 8);
}

void fb_fill_rect_alpha(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color, uint8_t alpha) {
    if (!g_fb_addr) return;
    if (x + w > g_fb_width) w = g_fb_width - x;
    if (y + h > g_fb_height) h = g_fb_height - y;

    for (uint32_t row = 0; row < h; row++) {
        uint32_t *line = &g_fb_addr[(y + row) * g_fb_pitch + x];
        for (uint32_t col = 0; col < w; col++) {
            line[col] = blend_color(color, line[col], alpha);
        }
    }
}

/* ============================================================
 * Wallpaper Support (simple gradient for now)
 * ============================================================ */
void fb_draw_wallpaper(void) {
    if (!g_fb_addr) return;

    /* macOS-style gradient: dark blue to purple */
    for (uint32_t y = 0; y < g_fb_height; y++) {
        float t = (float)y / g_fb_height;
        uint32_t r = (uint32_t)(30 + t * 20);
        uint32_t g = (uint32_t)(30 + t * 10);
        uint32_t b = (uint32_t)(46 + t * 30);
        uint32_t color = (0xFF << 24) | (r << 16) | (g << 8) | b;

        uint32_t *line = &g_fb_addr[y * g_fb_pitch];
        for (uint32_t x = 0; x < g_fb_width; x++) {
            line[x] = color;
        }
    }
}