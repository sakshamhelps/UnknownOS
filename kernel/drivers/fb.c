/* ============================================================
 * Init
 * ============================================================ */
void fb_init(struct boot_info *boot_info) {
    struct limine_framebuffer_response *fb_resp = boot_info->framebuffer;

    if (!fb_resp || fb_resp->framebuffer_count == 0) {
        serial_puts("[FB] No framebuffer available\n");
        return;
    }

    g_fb = fb_resp->framebuffers[0];
    g_fb_addr = (uint32_t *)((uint64_t)g_fb->address + boot_info->hhdm->offset);
    g_fb_width = g_fb->width;
    g_fb_height = g_fb->height;
    g_fb_pitch = g_fb->pitch / 4;  // pixels per row
    g_fb_bpp = g_fb->bpp;

    serial_printf("[FB] %ux%u @ %u bpp, pitch %u, addr 0x%lx\n",
                  g_fb_width, g_fb_height, g_fb_bpp, g_fb_pitch, (uint64_t)g_fb_addr);

    /* Clear to background */
    fb_clear(COLOR_BG);
}

bool fb_available(void) {
    return g_fb_addr != NULL;
}

uint32_t fb_width(void) { return g_fb_width; }
uint32_t fb_height(void) { return g_fb_height; }
uint32_t fb_pitch(void) { return g_fb_pitch; }

/* ============================================================
 * Basic Drawing
 * ============================================================ */
static inline void fb_put_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (x >= g_fb_width || y >= g_fb_height) return;
    g_fb_addr[y * g_fb_pitch + x] = color;
}

void fb_clear(uint32_t color) {
    if (!g_fb_addr) return;
    for (uint32_t y = 0; y < g_fb_height; y++) {
        for (uint32_t x = 0; x < g_fb_width; x++) {
            g_fb_addr[y * g_fb_pitch + x] = color;
        }
    }
}

void fb_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    if (!g_fb_addr) return;
    if (x + w > g_fb_width) w = g_fb_width - x;
    if (y + h > g_fb_height) h = g_fb_height - y;

    for (uint32_t row = 0; row < h; row++) {
        uint32_t *line = &g_fb_addr[(y + row) * g_fb_pitch + x];
        for (uint32_t col = 0; col < w; col++) {
            line[col] = color;
        }
    }
}

void fb_draw_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    fb_fill_rect(x, y, w, 1, color);
    fb_fill_rect(x, y + h - 1, w, 1, color);
    fb_fill_rect(x, y, 1, h, color);
    fb_fill_rect(x + w - 1, y, 1, h, color);
}

void fb_draw_line(uint32_t x1, uint32_t y1, uint32_t x2, uint32_t y2, uint32_t color) {
    int dx = (x2 > x1) ? x2 - x1 : x1 - x2;
    int dy = (y2 > y1) ? y2 - y1 : y1 - y2;
    int sx = (x1 < x2) ? 1 : -1;
    int sy = (y1 < y2) ? 1 : -1;
    int err = dx - dy;

    while (true) {
        fb_put_pixel(x1, y1, color);
        if (x1 == x2 && y1 == y2) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x1 += sx; }
        if (e2 < dx) { err += dx; y1 += sy; }
    }
}

